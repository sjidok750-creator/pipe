# 단변수 확인: ξ1 = g(ν'*λ1L')
# g(0) = 0, g → 1 as arg → ∞
# x_half point (g=0.5): 3.0 (from ν'=0.20, x=15)
# g(0.3195) = 0.015

# 이것이 S자 함수라면 꽤 날카로운 모양 (0.015 at 0.32, 0.5 at 3.0)
import math
def g_test(u):
    # tanh 계열
    return 0.5*(1 + math.tanh(math.log(u) - math.log(3.0)))

print()
