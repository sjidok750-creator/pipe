// ============================================================
// 상부 토압 상수 — 세부지훈 11-134 (가) 작용 하중(외압)
//   Wv = γt·H              (H ≤ 2.0 m)
//   Wv = Cd·γt·B           (H > 2.0 m)
//   Cd = [1 − e^(−2kμ′·H/B)] / (2kμ′)
//   k  = (1−sinφ)/(1+sinφ),  μ′ = tanφ′,  φ′ = φ = 30°
//   γt = 1.8×10⁻³ kg/cm³,   B = 2D + 100
//
// ⚠ 단위: 원문 수식군 전체가 cm 계(H: cm, γt: kg/cm³)이므로
//   B = 2D + 100 의 D·B 도 cm 이다. mm로 해석하면 B가 과소평가되어
//   Cd가 커지는 것 이상으로 B가 작아져 Wv가 약 26% 낮게(위험측) 나온다.
//   검증: DN500 → B = 2×50.8+100 = 201.6 cm (지침 예제표 200 cm)
// ============================================================
export const EARTH_LOAD = {
  phi_deg: 30,                       // 매설토와 굴착면의 마찰각 φ′ = φ = 30° (11-134)
  get k()   { const s = Math.sin(this.phi_deg * Math.PI / 180); return (1 - s) / (1 + s) },
  get mu()  { return Math.tan(this.phi_deg * Math.PI / 180) },
  get kmu() { return this.k * this.mu },   // φ=30° → 0.19245
  gamma_t: 1.8e-3,                   // kg/cm³ — 흙의 단위중량
  H_limit_m: 2.0,                    // m — 이하 연직토압, 초과 Marston
  B_formula_cm: (Do_cm) => 2 * Do_cm + 100,  // cm — 강관 정부에서의 굴착부 폭
}

