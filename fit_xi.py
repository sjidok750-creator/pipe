# === ξ1 ===
# 그래프 관찰: 모든 곡선이 ν'*λ1L' = u 의 함수인 것으로 보임
# u=0 → 0, u=3 → 0.5, u→∞ → 1.0
# 앵커: ν'=0.019, λ1L'=16.818 → u=0.3195 → ξ1=0.015

# g(u) = 0.5*(1+tanh(k*(log(u)-log(u0))))
# 조건: g(u0)=0.5 → tanh(0)=0 → 항상 만족
# g(0.3195)=0.015: tanh(k*(log(0.3195)-log(u0)))=2*0.015-1=-0.97
# tanh^-1(-0.97) = -2.092 = k*(log(0.3195)-log(u0)) = k*(log(0.3195/u0))

# 두 번째 조건 필요. 그래프에서 ν'=0.2, x=40일 때 ξ1≈0.9를 사용:
# u = 0.2*40 = 8.0 → g(8)=0.9
# tanh(k*(log(8)-log(u0)))=0.8 → k*(log(8/u0))=0.973

# 연립:
# k*(log(0.3195/u0)) = -2.092  ...(1)
# k*(log(8/u0)) = 0.973        ...(2)
# (2)-(1): k*log(8/0.3195) = 0.973+2.092 = 3.065
# k*log(25.04) = 3.065
# k*3.220 = 3.065 → k = 0.952

k = 3.065 / math.log(8/0.3195)
print(f"k = {k:.4f}")

# log(u0)로부터:
# -2.092 = 0.952*(log(0.3195)-log(u0))
# -2.092/0.952 = log(0.3195)-log(u0)
# -2.197 = log(0.3195)-log(u0)
# log(u0) = log(0.3195)+2.197 = -1.140+2.197 = 1.057
# u0 = exp(1.057) = 2.878

log_u0 = math.log(0.3195) + 2.092/k
u0 = math.exp(log_u0)
print(f"u0 = {u0:.4f}")

def xi1_formula(nu_prime, lam1Lp):
    u = nu_prime * lam1Lp
    if u <= 0: return 0.0
    return min(1.0, max(0.0, 0.5*(1 + math.tanh(k * (math.log(u) - math.log(u0))))))

print()
print("=== ξ1 공식 검증 ===")
# 앵커
v = xi1_formula(0.019, 16.818)
print(f"앵커: ν'=0.019, x=16.818 → ξ1={v:.4f} (ref=0.015)")

# 그래프 독취 포인트 (ν'=0.20, 관찰값)
for x, xi_ref in [(5, 0.1), (10, 0.3), (15, 0.5), (25, 0.8), (40, 0.95), (80, 1.0)]:
    v = xi1_formula(0.20, x)
    print(f"ν'=0.20, x={x:3d}: ξ1={v:.3f} (graf≈{xi_ref})")

print()
for x, xi_ref in [(30, 0.5), (60, 0.8), (100, 0.95), (150, 0.99)]:
    v = xi1_formula(0.10, x)
    print(f"ν'=0.10, x={x:3d}: ξ1={v:.3f} (graf≈{xi_ref})")

print()
for x, xi_ref in [(150, 0.5), (300, 0.85), (500, 0.97)]:
    v = xi1_formula(0.02, x)
    print(f"ν'=0.02, x={x:3d}: ξ1={v:.3f} (graf≈{xi_ref})")

print()
