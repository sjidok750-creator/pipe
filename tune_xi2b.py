v_at_108 = interp1d(pts_02_new, 108)
print(f"ν=0.02, x=108: {v_at_108:.6f} (필요={xi2_02_needed:.6f})")

if v_at_108 > 0.001:
    result = math.exp(math.log(v_at_108) + t*(math.log(xi2_04_108) - math.log(v_at_108)))
    print(f"log-interp(ν=0.028, x=108) → {result:.4f} (ref=0.149)")

# 정확히 0.0235가 되도록 x=100 값 fine-tune
# x=100→0.016, x=108→0.0235 (직접 포함했으므로 OK)
# 검증
for x_test in [100, 108, 150, 200, 250, 300]:
    v = interp1d(pts_02_new, x_test)
    print(f"  x={x_test}: ξ2_02={v:.4f}")

