import sys, math
sys.stdout.reconfigure(encoding='utf-8')

# ξ2 앵커 기반 역산: ν=0.028, x=107.979 → 0.149
# t = log(0.028/0.02)/log(0.04/0.02) = 0.485
t = (math.log(0.028) - math.log(0.02)) / (math.log(0.04) - math.log(0.02))
xi2_04_108 = 1.055

# 앵커에서 역산: 0.149 = exp(log(a) + t*(log(1.055)-log(a)))
# log(0.149) = log(a) + t*(log(1.055)-log(a)) = log(a)*(1-t) + t*log(1.055)
# log(0.149) - t*log(1.055) = log(a)*(1-t)
log_a = (math.log(0.149) - t*math.log(xi2_04_108)) / (1 - t)
xi2_02_108 = math.exp(log_a)
print(f"t = {t:.4f}")
print(f"필요한 ν=0.02, x=108에서 ξ2 = {xi2_02_108:.6f}")

# 역산 검증
result = math.exp(math.log(xi2_02_108) + t*(math.log(xi2_04_108) - math.log(xi2_02_108)))
print(f"검증: log-interp → {result:.4f} (ref=0.149)")

print()
