def interp1d(pts, x):
    if x <= pts[0][0]: return pts[0][1]
    if x >= pts[-1][0]: return pts[-1][1]
    for i in range(len(pts)-1):
        if pts[i][0] <= x <= pts[i+1][0]:
            tt = (x - pts[i][0]) / (pts[i+1][0] - pts[i][0])
            return pts[i][1] + tt * (pts[i+1][1] - pts[i][1])
    return pts[-1][1]

xi2_02_test = interp1d(pts_02, 108)
print(f"테스트 테이블 ν=0.02, x=108 → {xi2_02_test:.6f} (필요={xi2_02_108:.6f})")

if xi2_02_test > 0.001 and xi2_04_108 > 0.001:
    result2 = math.exp(math.log(xi2_02_test) + t*(math.log(xi2_04_108) - math.log(xi2_02_test)))
    print(f"log-interp (ν=0.028, x=108) → {result2:.4f} (ref=0.149)")

